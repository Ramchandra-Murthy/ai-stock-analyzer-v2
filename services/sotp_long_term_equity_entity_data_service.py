def _reconcile_annexure_to_note_39(
    population: list[dict[str, Any]],
    annexure_entities: list[dict[str, Any]],
) -> dict[str, Any]:
    """
    Reconcile Annexure A evidence records against the
    authoritative Note 39 associate/JV population.

    A match requires the normalized legal entity name
    to match exactly.

    Ownership percentages are checked separately and
    do not determine entity identity.
    """

    population_by_name: dict[str, dict[str, Any]] = {}

    for entity in population:
        normalized_name = _normalize_entity_name(entity.get("name"))

        if normalized_name:
            population_by_name[normalized_name] = entity

    matched_entities: list[dict[str, Any]] = []
    unmatched_entities: list[dict[str, Any]] = []

    for annexure_entity in annexure_entities:

        annexure_name = str(annexure_entity.get("name") or "").strip()

        normalized_name = _normalize_entity_name(annexure_name)

        population_entity = population_by_name.get(normalized_name)

        if population_entity is None:

            exception = RELIANCE_ANNEXURE_NOTE_39_EXCEPTIONS.get(normalized_name)

            if exception is not None:
                unmatched_entities.append(
                    {
                        "name": annexure_name,
                        "reason": ("DOCUMENTED_DISCLOSURE_EXCEPTION"),
                        **dict(exception),
                    }
                )
            else:
                unmatched_entities.append(
                    {
                        "name": annexure_name,
                        "reason": ("NOT_FOUND_IN_NOTE_39_POPULATION"),
                        "resolution_status": "UNRESOLVED",
                    }
                )

            continue

        annexure_ownership = _safe_float(annexure_entity.get("ownership_percent"))

        note_39_ownership = _safe_float(population_entity.get("ownership_percent"))

        ownership_match = (
            annexure_ownership is not None
            and note_39_ownership is not None
            and abs(annexure_ownership - note_39_ownership) < 0.001
        )

        matched_entities.append(
            {
                "name": annexure_name,
                "note_39_serial": (population_entity.get("note_39_serial")),
                "annexure_ownership_percent": (annexure_ownership),
                "note_39_ownership_percent": (note_39_ownership),
                "ownership_match": ownership_match,
            }
        )

    explained_exceptions = [
        entity for entity in unmatched_entities if entity.get("resolution_status") == "EXPLAINED"
    ]

    unresolved_exceptions = [
        entity for entity in unmatched_entities if entity.get("resolution_status") != "EXPLAINED"
    ]

    ownership_mismatches = [entity for entity in matched_entities if not entity["ownership_match"]]

    return {
        "annexure_count": len(annexure_entities),
        "matched_count": len(matched_entities),
        "unmatched_count": len(unmatched_entities),
        "explained_exception_count": len(explained_exceptions),
        "unresolved_exception_count": len(unresolved_exceptions),
        "ownership_mismatch_count": len(ownership_mismatches),
        "matched_entities": matched_entities,
        "unmatched_entities": unmatched_entities,
        "explained_exceptions": explained_exceptions,
        "unresolved_exceptions": unresolved_exceptions,
        "ownership_mismatches": ownership_mismatches,
    }


def get_sotp_long_term_equity_entity_data(
    symbol: str,
) -> dict[str, Any]:

    symbol = str(symbol or "").upper().strip()

    if symbol.endswith(".NS"):
        symbol = symbol[:-3]

    if symbol != "RELIANCE":
        return {
            "status": "UNAVAILABLE",
            "version": "V5.0",
            "symbol": symbol,
            "message": (
                "Entity-level long-term equity evidence " "is not configured for this symbol."
            ),
        }

    # ======================================================
    # AUTHORITATIVE NOTE 39 POPULATION
    # ======================================================

    population = [dict(entity) for entity in RELIANCE_LONG_TERM_EQUITY_POPULATION]

    population_count = len(population)

    population_validation = _validate_note_39_population(population)

    population_with_ownership = sum(
        1 for entity in population if _safe_float(entity.get("ownership_percent")) is not None
    )

    # ======================================================
    # ANNEXURE A ENTITY-LEVEL EVIDENCE
