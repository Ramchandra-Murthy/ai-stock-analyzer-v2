def _safe_float(value: Any):
    try:
        if value is None:
            return None

        value = float(value)

        if value != value:
            return None

        return value

    except (TypeError, ValueError):
        return None


def _validate_note_39_population(
    population: list[dict[str, Any]],
) -> dict[str, Any]:

    expected_count = RELIANCE_NOTE_39_EXPECTED_POPULATION_COUNT
    expected_serials = set(range(1, expected_count + 1))

    actual_count = len(population)

    serials: list[int] = []
    names: list[str] = []

    missing_name_serials: list[int] = []
    missing_country_serials: list[int] = []
    missing_ownership_serials: list[int] = []
    invalid_ownership_serials: list[int] = []
    invalid_serial_rows: list[int] = []

    for row_index, entity in enumerate(population, start=1):

        serial = entity.get("note_39_serial")

        if isinstance(serial, int):
            serials.append(serial)
        else:
            invalid_serial_rows.append(row_index)

        name = str(entity.get("name") or "").strip()

        if name:
            names.append(name)
        elif isinstance(serial, int):
            missing_name_serials.append(serial)

        country = str(entity.get("country") or "").strip()

        if not country and isinstance(serial, int):
            missing_country_serials.append(serial)

        ownership = _safe_float(entity.get("ownership_percent"))

        if ownership is None:
            if isinstance(serial, int):
                missing_ownership_serials.append(serial)

        elif not (0.0 <= ownership <= 100.0):
            if isinstance(serial, int):
                invalid_ownership_serials.append(serial)

    serial_set = set(serials)

    missing_serials = sorted(expected_serials - serial_set)

    unexpected_serials = sorted(serial_set - expected_serials)

    duplicate_serials = sorted({serial for serial in serials if serials.count(serial) > 1})

    normalized_names = [name.casefold() for name in names]

    duplicate_names = sorted(
        {
            names[index]
            for index, normalized_name in enumerate(normalized_names)
            if normalized_names.count(normalized_name) > 1
        }
    )

    population_valid = all(
        [
            actual_count == expected_count,
            len(serials) == expected_count,
            not invalid_serial_rows,
            not missing_serials,
            not unexpected_serials,
            not duplicate_serials,
            not duplicate_names,
            not missing_name_serials,
            not missing_country_serials,
            not missing_ownership_serials,
            not invalid_ownership_serials,
        ]
    )

    return {
        "expected_count": expected_count,
        "actual_count": actual_count,
        "serial_count": len(serials),
        "missing_serials": missing_serials,
        "unexpected_serials": unexpected_serials,
        "duplicate_serials": duplicate_serials,
        "duplicate_names": duplicate_names,
        "invalid_serial_rows": invalid_serial_rows,
        "missing_name_serials": missing_name_serials,
        "missing_country_serials": missing_country_serials,
        "missing_ownership_serials": missing_ownership_serials,
        "invalid_ownership_serials": invalid_ownership_serials,
        "population_valid": population_valid,
    }


def _normalize_entity_name(value: Any) -> str:
    """
    Normalize an entity name for conservative exact matching.

    This is intentionally limited to case, whitespace,
    and dash normalization. It does not perform fuzzy
    matching or infer that differently named legal
    entities are equivalent.
    """

    normalized = str(value or "").casefold().strip()

    normalized = normalized.replace("\u2010", "-")
    normalized = normalized.replace("\u2011", "-")
    normalized = normalized.replace("\u2012", "-")
    normalized = normalized.replace("\u2013", "-")
    normalized = normalized.replace("\u2014", "-")
    normalized = normalized.replace("\u2212", "-")

    return " ".join(normalized.split())


